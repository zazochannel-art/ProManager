#!/usr/bin/env node
/**
 * Generates src/types/database.ts from a PostgreSQL database that has the
 * ProManager migrations applied, in the same shape as `supabase gen types`.
 *
 * Preferred in a real project:  npx supabase gen types typescript --local > src/types/database.ts
 * This script exists so types can be regenerated without the Supabase CLI
 * (e.g. against the plain-Postgres test database used in CI).
 *
 * Usage: DATABASE_URL=postgres://... node scripts/generate-db-types.mjs
 */
import { writeFileSync } from "node:fs";
import pg from "pg";

const url = process.env.DATABASE_URL;
if (!url) {
  console.error("DATABASE_URL is required");
  process.exit(1);
}

const client = new pg.Client({ connectionString: url });
await client.connect();

const PG_TO_TS = {
  uuid: "string", text: "string", bpchar: "string", varchar: "string", citext: "string",
  int2: "number", int4: "number", int8: "number", float4: "number", float8: "number",
  // NUMERIC is returned by PostgREST as a JSON number; the app converts it to a
  // decimal string immediately (see src/lib/calculations/decimal.ts).
  numeric: "Numeric",
  bool: "boolean", date: "string", timestamptz: "string", timestamp: "string", time: "string",
  jsonb: "Json", json: "Json", bytea: "string", inet: "string",
};

const enums = (await client.query(`
  select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid
  join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`)).rows;
const enumNames = new Set(enums.map((e) => e.name));

function tsType(udt, isArray) {
  const base = udt.replace(/^_/, "");
  let t = enumNames.has(base) ? `Database["public"]["Enums"]["${base}"]` : PG_TO_TS[base] ?? "unknown";
  if (isArray || udt.startsWith("_")) t = `${t}[]`;
  return t;
}

const cols = (await client.query(`
  select c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default, c.is_generated,
         c.is_identity, c.identity_generation, t.table_type
  from information_schema.columns c
  join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public'
  order by c.table_name, c.ordinal_position`)).rows;

const tables = new Map();
const views = new Map();
for (const c of cols) {
  const target = c.table_type === "VIEW" ? views : tables;
  if (!target.has(c.table_name)) target.set(c.table_name, []);
  target.get(c.table_name).push(c);
}

const fns = (await client.query(`
  select p.proname as name,
         pg_get_function_arguments(p.oid) as args_sig,
         coalesce(p.proargnames::text[], array[]::text[]) as arg_names,
         array(select format_type(unnest(p.proargtypes), null))::text[] as arg_types,
         p.pronargdefaults as n_defaults,
         format_type(p.prorettype, null) as ret,
         pg_get_function_result(p.oid) as ret_full,
         p.proretset as returns_set,
         t.typname as ret_typname
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  join pg_type t on t.oid = p.prorettype
  where n.nspname = 'public' and p.prokind = 'f'
  order by p.proname`)).rows;

function fmtTypeToTs(fmt) {
  const map = {
    uuid: "string", text: "string", "character(2)": "string", "character(3)": "string", character: "string",
    integer: "number", bigint: "number", numeric: "Numeric", boolean: "boolean", date: "string",
    jsonb: "Json", json: "Json", "timestamp with time zone": "string", void: "undefined",
  };
  if (map[fmt]) return map[fmt];
  const name = fmt.replace(/^public\./, "");
  if (enumNames.has(name)) return `Database["public"]["Enums"]["${name}"]`;
  if (tables.has(name)) return `Database["public"]["Tables"]["${name}"]["Row"]`;
  return "unknown";
}

let out = `// AUTO-GENERATED by scripts/generate-db-types.mjs — do not edit by hand.
// Regenerate after changing migrations: npm run db:types

/** NUMERIC columns: PostgREST returns JSON numbers; we send exact decimal strings. Always read through dec(). */
export type Numeric = number | string;

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;

for (const [name, columns] of tables) {
  const row = columns.map((c) => `          ${c.column_name}: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`).join("\n");
  const writable = columns.filter((c) => c.is_generated !== "ALWAYS" && c.identity_generation !== "ALWAYS");
  const insert = writable.map((c) => {
    const optional = c.is_nullable === "YES" || c.column_default !== null || c.is_identity === "YES";
    return `          ${c.column_name}${optional ? "?" : ""}: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`;
  }).join("\n");
  const update = writable.map((c) => `          ${c.column_name}?: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`).join("\n");
  out += `      ${name}: {
        Row: {
${row}
        };
        Insert: {
${insert}
        };
        Update: {
${update}
        };
        Relationships: [];
      };
`;
}

out += `    };
    Views: {
`;
for (const [name, columns] of views) {
  const row = columns.map((c) => `          ${c.column_name}: ${tsType(c.udt_name)} | null;`).join("\n");
  out += `      ${name}: {
        Row: {
${row}
        };
        Relationships: [];
      };
`;
}
out += `    };
    Functions: {
`;
for (const f of fns) {
  if (f.ret === "trigger") continue;
  const required = f.arg_types.length - f.n_defaults;
  const args = f.arg_types.map((t, i) => {
    const n = f.arg_names[i] ?? `arg${i}`;
    return `${n}${i >= required ? "?" : ""}: ${fmtTypeToTs(t)}`;
  });
  let ret = fmtTypeToTs(f.ret);
  if (f.ret_full.startsWith("TABLE(")) {
    const inner = f.ret_full.slice(6, -1);
    const fields = inner.split(", ").map((part) => {
      const [col, ...type] = part.split(" ");
      return `${col}: ${fmtTypeToTs(type.join(" "))}`;
    });
    ret = `{ ${fields.join("; ")} }`;
  } else if (f.ret === "record" || f.ret_typname === "record") {
    ret = "Record<string, unknown>";
  }
  if (f.returns_set) ret = `${ret}[]`;
  out += `      ${f.name}: {
        Args: ${args.length ? `{ ${args.join("; ")} }` : "Record<PropertyKey, never>"};
        Returns: ${ret};
      };
`;
}
out += `    };
    Enums: {
`;
for (const e of enums) {
  out += `      ${e.name}: ${e.labels.map((l) => JSON.stringify(l)).join(" | ")};\n`;
}
out += `    };
    CompositeTypes: Record<string, never>;
  };
};

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Views<T extends keyof PublicSchema["Views"]> = PublicSchema["Views"][T]["Row"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;

writeFileSync(new URL("../src/types/database.ts", import.meta.url), out);
await client.end();
console.log(`Wrote src/types/database.ts (${tables.size} tables, ${views.size} views, ${fns.length} functions)`);
